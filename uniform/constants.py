# ---------------------------------------------------------------------------
# Разметка рук по форматам скина
# ---------------------------------------------------------------------------

def _rect(x, y, width, height):
    """Прямоугольник пикселей текстуры."""
    return [(x + dx, y + dy) for dx in range(width) for dy in range(height)]


def box_uv_cells(u, v, w, h, d):
    """
    Пиксели текстуры, которые занимает куб ``w × h × d`` с началом box-UV ``(u, v)``.

    Порядок граней — как в box-UV Minecraft/Blockbench: верх, низ, внешняя
    боковая, передняя, внутренняя боковая, задняя. Списки ``*_main`` выше
    описывают ровно эти ячейки (проверяется тестом для всех шести частей тела).

    Пример: ``box_uv_cells(40, 16, 4, 12, 4)`` совпадает с ``right_arm_main``,
    а ``box_uv_cells(40, 16, 3, 12, 4)`` — это та же рука, но у slim-скина.
    """
    return sorted(
        _rect(u + d, v, w, d)                    # верх
        + _rect(u + d + w, v, w, d)              # низ
        + _rect(u, v + d, d, h)                  # внешняя боковая
        + _rect(u + d, v + d, w, h)              # передняя
        + _rect(u + d + w, v + d, d, h)          # внутренняя боковая
        + _rect(u + d + w + d, v + d, w, h)      # задняя
    )


#: Правый рукав slim-скина: руки 3 пикселя шириной вместо 4.
right_arm_main_slim = box_uv_cells(40, 16, 3, 12, 4)

#: Левый рукав slim-скина.
left_arm_main_slim = box_uv_cells(32, 48, 3, 12, 4)

